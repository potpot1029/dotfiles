#!/usr/bin/env python3
"""Generate per-tool colour files from palette.toml.

Writes (paths relative to the dotfiles .config dir):
  palette/palette.lua            hyprland + nvim (dofile)
  ghostty/themes/custom-synthwave
  tmux/tmux.conf                 %hidden variables block between markers
  waybar/colors.css              @define-color, imported by style.css
  hypr/colors.conf               $variables, sourced by hyprlock.conf
  starship.toml                  [palettes.synthwave] block between markers
"""

import re
import sys
import tomllib
from pathlib import Path

CONFIG = Path(__file__).resolve().parent.parent
HEADER = "generated by ~/.config/palette/generate.py from palette.toml; do not edit"

with open(CONFIG / "palette" / "palette.toml", "rb") as f:
    data = tomllib.load(f)

colors: dict[str, str] = data["colors"]
for name, value in colors.items():
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        sys.exit(f"palette.toml: {name} = {value!r} is not #rrggbb")


def resolve(ref: str) -> str:
    if ref.startswith("#"):
        return ref
    if ref not in colors:
        sys.exit(f"palette.toml: unknown colour name {ref!r}")
    return colors[ref]


def write(rel: str, text: str) -> None:
    path = CONFIG / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text() if path.exists() else None
    if old != text:
        path.write_text(text)
        print(f"wrote    {rel}")
    else:
        print(f"same     {rel}")


START, END = "# >>> palette (generated)", "# <<< palette"
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)


def replace_block(rel: str, lines: list[str]) -> None:
    """Replace the text between the palette markers in an existing config file."""
    text = (CONFIG / rel).read_text()
    if not BLOCK.search(text):
        sys.exit(f"{rel}: missing '{START}' ... '{END}' markers")
    block = "\n".join([START, f"# {HEADER}", *lines, END])
    write(rel, BLOCK.sub(lambda _: block, text))


width = max(map(len, colors))

# lua: hyprland + nvim
lua = [f"-- {HEADER}", "return {"]
lua += [f'\t{n} = "{v}",' for n, v in colors.items()]
lua.append("}")
write("palette/palette.lua", "\n".join(lua) + "\n")

# ghostty theme
t = data["terminal"]
ghostty = [
    f"# {HEADER}",
    f"background = {resolve(t['background'])}",
    f"foreground = {resolve(t['foreground'])}",
    f"cursor-color = {resolve(t['cursor'])}",
    f"selection-background = {resolve(t['selection_background'])}",
    f"selection-foreground = {resolve(t['selection_foreground'])}",
    "",
]
ghostty += [f"palette = {i}={resolve(c)}" for i, c in enumerate(t["ansi"])]
write("ghostty/themes/custom-synthwave", "\n".join(ghostty) + "\n")

# tmux: %hidden NAME="#hex" block in tmux.conf, used as "$NAME"
replace_block("tmux/tmux.conf", [f'%hidden {n.upper()}="{v}"' for n, v in colors.items()])

# waybar
css = [f"/* {HEADER} */"]
css += [f"@define-color {n} {v};" for n, v in colors.items()]
write("waybar/colors.css", "\n".join(css) + "\n")

# hyprlang (hyprlock): $name = rgb(rrggbb)
hypr = [f"# {HEADER}"]
hypr += [f"${n:<{width}} = rgb({v[1:]})" for n, v in colors.items()]
write("hypr/colors.conf", "\n".join(hypr) + "\n")

# starship: [palettes.synthwave] block in starship.toml
replace_block("starship.toml", ["[palettes.synthwave]"] + [f'{n:<{width}} = "{v}"' for n, v in colors.items()])
